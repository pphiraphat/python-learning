# if statement มีรูป 3 แบบ คือ if, if-else, if-elif-else

# โปรแกรมตัดเกรดนักศึกษา
# คำนวณเกรดจากคะแนนสอบ โดยเกรฑ์ดังนี้ คะแนนสอบ >= 50 ได้เกรด A, คะแนนสอบ >= 40 ได้เกรด F

# input
score = int(input("กรุณากรอกคะแนนสอบของนักศึกษา: "))
print("คะแนนสอบของนักศึกษา:", score)

# process
if score <= 0:
    print("คะแนนสอบไม่ถูกต้อง")
elif score >= 50:
    print("นักศึกษาได้เกรด A")
else:
    print("นักศึกษาได้เกรด F")